EXEC(N'CREATE TRIGGER TR_COM_APPROVAL_HISTORY_APPEND_ONLY
ON COM_APPROVAL_HISTORY
AFTER UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    THROW 51219, ''COM_APPROVAL_HISTORY is append-only'', 1;
END');
