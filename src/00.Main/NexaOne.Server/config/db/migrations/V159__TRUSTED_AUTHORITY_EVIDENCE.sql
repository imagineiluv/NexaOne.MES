       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.SEQUENCE_RUN_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.SEQUENCE_RUN_ID))
       AND R.EQUIPMENT_ID COLLATE Latin1_General_100_BIN2
             = I.EQUIPMENT_ID COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.EQUIPMENT_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.EQUIPMENT_ID))
       AND R.OPERATION_KEY COLLATE Latin1_General_100_BIN2
             = I.OPERATION_KEY COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.OPERATION_KEY))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.OPERATION_KEY))
       AND R.RECIPE_ID COLLATE Latin1_General_100_BIN2
             = I.RECIPE_ID COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.RECIPE_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.RECIPE_ID))
       AND R.RECIPE_VERSION = I.RECIPE_VERSION
       AND R.SNAPSHOT_SCHEMA COLLATE Latin1_General_100_BIN2
             = I.RECIPE_SNAPSHOT_SCHEMA COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.SNAPSHOT_SCHEMA))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.RECIPE_SNAPSHOT_SCHEMA))
       AND R.SNAPSHOT_HASH COLLATE Latin1_General_100_BIN2
             = I.RECIPE_SNAPSHOT_HASH COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), R.SNAPSHOT_HASH))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.RECIPE_SNAPSHOT_HASH))
     WHERE R.EXECUTION_ID IS NULL)
    THROW 51562, ''Projection authority requires exact canonical recipe evidence'', 1;

  -- Acquire the immutable artifact row before the revocation key/range.
  IF EXISTS (
      SELECT 1 FROM inserted I
      LEFT JOIN SYS_RELEASED_PROGRAM_ARTIFACT A WITH (UPDLOCK, HOLDLOCK)
        ON A.ARTIFACT_ID COLLATE Latin1_General_100_BIN2
             = I.PROGRAM_ARTIFACT_ID COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.ARTIFACT_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.PROGRAM_ARTIFACT_ID))
       AND A.EQUIPMENT_ID COLLATE Latin1_General_100_BIN2
             = I.EQUIPMENT_ID COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.EQUIPMENT_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.EQUIPMENT_ID))
       AND A.OPERATION_KEY COLLATE Latin1_General_100_BIN2
             = I.OPERATION_KEY COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.OPERATION_KEY))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.OPERATION_KEY))
       AND A.PROGRAM_SCHEMA COLLATE Latin1_General_100_BIN2
             = I.PROGRAM_SCHEMA COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.PROGRAM_SCHEMA))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.PROGRAM_SCHEMA))
       AND A.PROGRAM_HASH COLLATE Latin1_General_100_BIN2
             = I.PROGRAM_HASH COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.PROGRAM_HASH))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.PROGRAM_HASH))
       AND A.BOUND_RECIPE_SNAPSHOT_SCHEMA COLLATE Latin1_General_100_BIN2
             = I.RECIPE_SNAPSHOT_SCHEMA COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.BOUND_RECIPE_SNAPSHOT_SCHEMA))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.RECIPE_SNAPSHOT_SCHEMA))
       AND A.BOUND_RECIPE_SNAPSHOT_HASH COLLATE Latin1_General_100_BIN2
             = I.RECIPE_SNAPSHOT_HASH COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), A.BOUND_RECIPE_SNAPSHOT_HASH))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.RECIPE_SNAPSHOT_HASH))
     WHERE A.ARTIFACT_ID IS NULL)
    THROW 51562, ''Projection authority requires an exact released program artifact'', 1;

  IF EXISTS (
      SELECT 1 FROM inserted I
      JOIN SYS_RELEASED_PROGRAM_ARTIFACT_REVOCATION V WITH (UPDLOCK, HOLDLOCK)
        ON V.ARTIFACT_ID COLLATE Latin1_General_100_BIN2
             = I.PROGRAM_ARTIFACT_ID COLLATE Latin1_General_100_BIN2
       AND DATALENGTH(CONVERT(NVARCHAR(MAX), V.ARTIFACT_ID))
             = DATALENGTH(CONVERT(NVARCHAR(MAX), I.PROGRAM_ARTIFACT_ID)))
    THROW 51563, ''Revoked program artifacts cannot acquire new projection authority'', 1;
END');
