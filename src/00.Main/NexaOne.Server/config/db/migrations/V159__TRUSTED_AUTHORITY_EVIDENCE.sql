              OR S.COMPLETE_QTY <> 0
              OR S.SCRAP_QTY <> 0
              OR S.SCOPE_TYPE COLLATE Latin1_General_100_BIN2
                   <> N''Other'' COLLATE Latin1_General_100_BIN2
              OR DATALENGTH(CONVERT(NVARCHAR(MAX), S.SCOPE_TYPE))
                   <> DATALENGTH(N''Other'')
              OR S.EQUIPMENT_ID IS NULL
              OR S.EQUIPMENT_ID COLLATE Latin1_General_100_BIN2 <> I.EQUIPMENT_ID
