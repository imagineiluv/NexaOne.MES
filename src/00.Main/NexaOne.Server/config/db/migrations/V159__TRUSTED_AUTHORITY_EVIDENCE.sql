-- A release coordinate deliberately excludes PROGRAM_HASH: one coordinate can identify exactly
-- one released payload. The seven NVARCHAR keys can occupy 1,800 bytes and therefore cannot be a
-- SQL Server unique key (limit: 1,700 bytes). Hash an unambiguous, length-prefixed UTF-16
-- serialization into a fixed 32-byte key instead. A SHA-256 collision fails closed by refusing the
-- second release; it can never allow two payloads at the same coordinate.
-- SQLite installs an equivalent full-coordinate BINARY guard during schema reconciliation.
-- SQLITE-OMIT-BEGIN
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET QUOTED_IDENTIFIER ON;
SET NUMERIC_ROUNDABORT OFF;
ALTER TABLE SYS_RELEASED_PROGRAM_ARTIFACT ADD RELEASE_COORDINATE_DIGEST AS
  CONVERT(BINARY(32), HASHBYTES('SHA2_256',
    CONCAT(
      N'E', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(EQUIPMENT_ID)), 10), EQUIPMENT_ID,
      N'O', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(OPERATION_KEY)), 10), OPERATION_KEY,
      N'R', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(PRODUCT_PROFILE_ID)), 10), PRODUCT_PROFILE_ID,
      N'P', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(PLUGIN_ID)), 10), PLUGIN_ID,
      N'D', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(PRODUCT_DEFINITION_VERSION)), 10), PRODUCT_DEFINITION_VERSION,
      N'V', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(PROGRAM_VERSION)), 10), PROGRAM_VERSION,
      N'S', RIGHT(REPLICATE(N'0', 10) + CONVERT(NVARCHAR(10), DATALENGTH(PROGRAM_SCHEMA)), 10), PROGRAM_SCHEMA))) PERSISTED;
CREATE UNIQUE INDEX UX_SYS_RELEASED_PROGRAM_ARTIFACT_COORDINATE_DIGEST
  ON SYS_RELEASED_PROGRAM_ARTIFACT(RELEASE_COORDINATE_DIGEST);
-- SQLITE-OMIT-END
