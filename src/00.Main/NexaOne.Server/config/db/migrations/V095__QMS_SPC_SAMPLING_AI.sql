-- QMS P1: append-only SPC evidence, sampling-plan revisions, and AI inspection audit.
CREATE TABLE QMS_SPC_LIMIT_REVISION (
    LIMIT_REVISION_ID NVARCHAR(50) NOT NULL,
    PARAM_ID NVARCHAR(50) NOT NULL,
    REVISION_NO INT NOT NULL,
    CHART_TYPE NVARCHAR(40) NOT NULL,
    CENTER_LINE DECIMAL(18,6) NOT NULL,
    UCL DECIMAL(18,6) NOT NULL,
    LCL DECIMAL(18,6) NOT NULL,
    EFFECTIVE_FROM DATETIME2 NOT NULL,
    REASON NVARCHAR(500) NULL,
    CREATED_BY NVARCHAR(50) NOT NULL,
    CREATED_AT DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPC_LIMIT_REV PRIMARY KEY (LIMIT_REVISION_ID),
    CONSTRAINT UQ_QMS_SPC_LIMIT_REV UNIQUE (PARAM_ID, REVISION_NO),
    CONSTRAINT FK_QMS_SPC_LIMIT_PARAM FOREIGN KEY (PARAM_ID) REFERENCES QMS_SPC_PARAM (PARAM_ID),
    CONSTRAINT CK_QMS_SPC_LIMIT_ORDER CHECK (REVISION_NO > 0 AND UCL > CENTER_LINE AND CENTER_LINE > LCL)
);
CREATE INDEX IX_QMS_SPC_LIMIT_EFFECTIVE ON QMS_SPC_LIMIT_REVISION (PARAM_ID, EFFECTIVE_FROM DESC);

