CREATE TABLE QMS_SAMPLING_PLAN_REVISION (
    PLAN_REVISION_ID NVARCHAR(50) NOT NULL,
    PLAN_ID NVARCHAR(50) NOT NULL,
    REVISION_NO INT NOT NULL,
    INSPECTION_MODE NVARCHAR(20) NOT NULL,
    LOT_SIZE_MIN INT NOT NULL,
    LOT_SIZE_MAX INT NULL,
    SAMPLE_SIZE INT NULL,
    ACCEPTANCE_NO INT NOT NULL,
    REJECTION_NO INT NOT NULL,
    AQL DECIMAL(9,4) NOT NULL,
    STANDARD_NAME NVARCHAR(100) NOT NULL,
    STANDARD_VERSION NVARCHAR(50) NOT NULL,
    EFFECTIVE_FROM DATETIME2 NOT NULL,
    CREATED_BY NVARCHAR(50) NOT NULL,
    CREATED_AT DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SAMPLING_PLAN_REV PRIMARY KEY (PLAN_REVISION_ID),
    CONSTRAINT UQ_QMS_SAMPLING_PLAN_REV UNIQUE (PLAN_ID, REVISION_NO),
    CONSTRAINT CK_QMS_SAMPLING_PLAN_MODE CHECK (INSPECTION_MODE IN ('Full', 'Sampling')),
    CONSTRAINT CK_QMS_SAMPLING_PLAN_RANGE CHECK (REVISION_NO > 0 AND LOT_SIZE_MIN > 0 AND
        (LOT_SIZE_MAX IS NULL OR LOT_SIZE_MAX >= LOT_SIZE_MIN) AND
        ((INSPECTION_MODE = 'Full' AND SAMPLE_SIZE IS NULL) OR
         (INSPECTION_MODE = 'Sampling' AND SAMPLE_SIZE > 0)) AND
        ACCEPTANCE_NO >= 0 AND REJECTION_NO = ACCEPTANCE_NO + 1 AND AQL >= 0 AND AQL <= 100)
);
CREATE INDEX IX_QMS_SAMPLING_PLAN_EFFECTIVE ON QMS_SAMPLING_PLAN_REVISION (PLAN_ID, EFFECTIVE_FROM DESC);

