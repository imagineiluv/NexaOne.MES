CREATE TABLE QMS_AI_INFERENCE (
    INFERENCE_ID NVARCHAR(80) NOT NULL,
    IDEMPOTENCY_KEY NVARCHAR(100) NOT NULL,
    MODEL_VERSION_ID NVARCHAR(50) NOT NULL,
    INSPECTION_ID NVARCHAR(50) NOT NULL,
    IMAGE_URI NVARCHAR(1000) NOT NULL,
    IMAGE_SHA256 CHAR(64) NOT NULL,
    RAW_VERDICT NVARCHAR(20) NOT NULL,
    CONFIDENCE DECIMAL(9,6) NOT NULL,
    THRESHOLD DECIMAL(9,6) NOT NULL,
    INFERRED_AT DATETIME2 NOT NULL,
    REQUEST_HASH CHAR(64) NOT NULL,
    CREATED_BY NVARCHAR(50) NOT NULL,
    CREATED_AT DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_AI_INFERENCE PRIMARY KEY (INFERENCE_ID),
    CONSTRAINT UQ_QMS_AI_INFERENCE_KEY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT FK_QMS_AI_INFERENCE_MODEL FOREIGN KEY (MODEL_VERSION_ID) REFERENCES QMS_AI_MODEL_VERSION (MODEL_VERSION_ID),
    CONSTRAINT FK_QMS_AI_INFERENCE_INSPECTION FOREIGN KEY (INSPECTION_ID) REFERENCES QMS_INSPECTION (INSPECTION_ID),
    CONSTRAINT CK_QMS_AI_INFERENCE CHECK (RAW_VERDICT IN ('Pass', 'Fail', 'Unknown') AND
        CONFIDENCE >= 0 AND CONFIDENCE <= 1 AND THRESHOLD >= 0 AND THRESHOLD <= 1)
);
CREATE INDEX IX_QMS_AI_INFERENCE_INSPECTION ON QMS_AI_INFERENCE (INSPECTION_ID, INFERRED_AT DESC);

