        REFERENCES IVT_BUSINESS_SCOPE (TENANT_ID, ORGANIZATION_ID),
    CONSTRAINT FK_IVT_STOCK_AUDIT_USER FOREIGN KEY (USER_ID) REFERENCES SYS_BUSINESS_IDENTITY (BUSINESS_USER_ID)
);
