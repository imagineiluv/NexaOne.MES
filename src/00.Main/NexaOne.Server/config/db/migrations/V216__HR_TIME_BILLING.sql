CREATE TABLE HR_TASK (
    TENANT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    ORGANIZATION_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    TASK_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    VERSION VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    NAME NVARCHAR(255) NOT NULL,
    PROJECT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    IS_ACTIVE BIT NOT NULL,
    CREATED_BY VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CONSTRAINT PK_HR_TASK PRIMARY KEY (TENANT_ID,ORGANIZATION_ID,TASK_ID),
    CONSTRAINT FK_HR_TASK_PROJECT FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,PROJECT_ID)
        REFERENCES CRM_PROJECT (TENANT_ID,ORGANIZATION_ID,PROJECT_ID),
    CONSTRAINT FK_HR_TASK_USER FOREIGN KEY (CREATED_BY)
        REFERENCES SYS_BUSINESS_IDENTITY (BUSINESS_USER_ID),
    CONSTRAINT CK_HR_TASK_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);

CREATE TABLE HR_TIMESHEET (
    TENANT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    ORGANIZATION_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    TIMESHEET_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    VERSION VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    EMPLOYEE_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    START_TICKS BIGINT NOT NULL,
    END_TICKS BIGINT NOT NULL,
    STATE INT NOT NULL,
    PAYLOAD NVARCHAR(MAX) NOT NULL,
    CONSTRAINT PK_HR_TIMESHEET PRIMARY KEY (TENANT_ID,ORGANIZATION_ID,TIMESHEET_ID),
    CONSTRAINT FK_HR_TIMESHEET_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES SYS_BUSINESS_IDENTITY (BUSINESS_USER_ID),
    CONSTRAINT CK_HR_TIMESHEET_RANGE CHECK (END_TICKS>START_TICKS),
    CONSTRAINT CK_HR_TIMESHEET_STATE CHECK (STATE BETWEEN 0 AND 2)
);

CREATE TABLE HR_TIME_ENTRY (
    TENANT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    ORGANIZATION_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    TIME_ENTRY_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    VERSION VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    EMPLOYEE_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    START_TICKS BIGINT NOT NULL,
    END_TICKS BIGINT NULL,
    PROJECT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    TASK_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    TIMESHEET_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    PAYLOAD NVARCHAR(MAX) NOT NULL,
    CONSTRAINT PK_HR_TIME_ENTRY PRIMARY KEY (TENANT_ID,ORGANIZATION_ID,TIME_ENTRY_ID),
    CONSTRAINT FK_HR_TIME_ENTRY_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES SYS_BUSINESS_IDENTITY (BUSINESS_USER_ID),
    CONSTRAINT FK_HR_TIME_ENTRY_PROJECT FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,PROJECT_ID)
        REFERENCES CRM_PROJECT (TENANT_ID,ORGANIZATION_ID,PROJECT_ID),
    CONSTRAINT FK_HR_TIME_ENTRY_TASK FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,TASK_ID)
        REFERENCES HR_TASK (TENANT_ID,ORGANIZATION_ID,TASK_ID),
    CONSTRAINT FK_HR_TIME_ENTRY_TIMESHEET FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,TIMESHEET_ID)
        REFERENCES HR_TIMESHEET (TENANT_ID,ORGANIZATION_ID,TIMESHEET_ID),
    CONSTRAINT CK_HR_TIME_ENTRY_RANGE CHECK (END_TICKS IS NULL OR END_TICKS>START_TICKS)
);
CREATE UNIQUE INDEX UQ_HR_TIME_ENTRY_RUNNING ON HR_TIME_ENTRY
    (TENANT_ID,ORGANIZATION_ID,EMPLOYEE_ID) WHERE END_TICKS IS NULL;
CREATE INDEX IX_HR_TIME_ENTRY_PERIOD ON HR_TIME_ENTRY
    (TENANT_ID,ORGANIZATION_ID,EMPLOYEE_ID,START_TICKS,END_TICKS);
CREATE INDEX IX_HR_TIMESHEET_PERIOD ON HR_TIMESHEET
    (TENANT_ID,ORGANIZATION_ID,EMPLOYEE_ID,START_TICKS,END_TICKS);

