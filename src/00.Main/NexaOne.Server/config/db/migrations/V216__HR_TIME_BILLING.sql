CREATE TABLE ERP_BILLING_TIME_SOURCE (
    TENANT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    ORGANIZATION_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    TIME_ENTRY_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CONTACT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    EMPLOYEE_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    PROJECT_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    TASK_ID VARCHAR(36) COLLATE Latin1_General_100_BIN2 NULL,
    OCCURRED_ON CHAR(10) COLLATE Latin1_General_100_BIN2 NOT NULL,
    DURATION_TICKS BIGINT NOT NULL,
    CURRENCY CHAR(3) COLLATE Latin1_General_100_BIN2 NOT NULL,
    DESCRIPTION NVARCHAR(255) NOT NULL,
    HOURLY_RATE VARCHAR(64) COLLATE Latin1_General_100_BIN2 NOT NULL,
    APPLY_TAX BIT NOT NULL,
    APPLY_DISCOUNT BIT NOT NULL,
    CREATED_BY VARCHAR(36) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CREATED_AT_TICKS BIGINT NOT NULL,
    CONSTRAINT PK_ERP_BILLING_TIME_SOURCE PRIMARY KEY (TENANT_ID,ORGANIZATION_ID,TIME_ENTRY_ID),
    CONSTRAINT FK_ERP_BILLING_TIME_SOURCE_ENTRY FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,TIME_ENTRY_ID)
        REFERENCES HR_TIME_ENTRY (TENANT_ID,ORGANIZATION_ID,TIME_ENTRY_ID),
    CONSTRAINT FK_ERP_BILLING_TIME_SOURCE_CONTACT FOREIGN KEY (TENANT_ID,ORGANIZATION_ID,CONTACT_ID)
        REFERENCES ERP_BILLING_CONTACT (TENANT_ID,ORGANIZATION_ID,CONTACT_ID),
    CONSTRAINT FK_ERP_BILLING_TIME_SOURCE_USER FOREIGN KEY (CREATED_BY)
        REFERENCES SYS_BUSINESS_IDENTITY (BUSINESS_USER_ID),
    CONSTRAINT CK_ERP_BILLING_TIME_SOURCE_DURATION CHECK (DURATION_TICKS>0),
    CONSTRAINT CK_ERP_BILLING_TIME_SOURCE_FLAGS CHECK (APPLY_TAX IN (0,1) AND APPLY_DISCOUNT IN (0,1))
);
CREATE INDEX IX_ERP_BILLING_TIME_SOURCE_CANDIDATE ON ERP_BILLING_TIME_SOURCE
    (TENANT_ID,ORGANIZATION_ID,CONTACT_ID,CURRENCY,OCCURRED_ON,TIME_ENTRY_ID);
