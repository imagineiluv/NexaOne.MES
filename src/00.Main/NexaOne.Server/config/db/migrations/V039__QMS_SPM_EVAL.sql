-- QMS Module: 협력사 관리(SPM) — 평가 항목/정의/정보연결/실적 + 시정 조치.
-- SmartUX QMS 협력사 관리 메뉴의 평가 업무화면이 "no such table"로 막혀 있어 화면 점등 백엔드로 5개 테이블을
-- 신설한다. 컬럼/감사/제약은 V030/V037/V038 QMS 스타일과 정합. SUPPLIER_ID는 협력사 마스터 미존재로
-- 소프트 참조(FK 생략). PARAM은 DEF/ITEM FK 보유(상위 선생성). SQLite는 방언 변환·FK 비강제.

-- 협력사 평가 항목 마스터.
CREATE TABLE QMS_SPM_EVAL_ITEM (
    ITEM_ID         NVARCHAR(50)    NOT NULL,
    ITEM_NAME       NVARCHAR(200)   NOT NULL,
    CATEGORY        NVARCHAR(50)    NULL,
    MAX_SCORE       INT             NULL,
    DESCRIPTION     NVARCHAR(500)   NULL,
    IS_ACTIVE       BIT             NOT NULL DEFAULT 1,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPM_EVAL_ITEM PRIMARY KEY (ITEM_ID)
);
CREATE INDEX IX_QMS_SPM_EVAL_ITEM_NAME ON QMS_SPM_EVAL_ITEM (ITEM_NAME);

-- 협력사 평가 정의(평가 양식/주기).
CREATE TABLE QMS_SPM_EVAL_DEF (
    DEF_ID          NVARCHAR(50)    NOT NULL,
    DEF_NAME        NVARCHAR(200)   NOT NULL,
    EVAL_CYCLE      NVARCHAR(50)    NULL,
    TARGET_TYPE     NVARCHAR(50)    NULL,
    DESCRIPTION     NVARCHAR(500)   NULL,
    IS_ACTIVE       BIT             NOT NULL DEFAULT 1,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPM_EVAL_DEF PRIMARY KEY (DEF_ID)
);
CREATE INDEX IX_QMS_SPM_EVAL_DEF_NAME ON QMS_SPM_EVAL_DEF (DEF_NAME);

-- 협력사 평가 정보 연결(정의↔항목 + 가중치).
CREATE TABLE QMS_SPM_EVAL_PARAM (
    PARAM_ID        NVARCHAR(50)    NOT NULL,
    DEF_ID          NVARCHAR(50)    NOT NULL,
    ITEM_ID         NVARCHAR(50)    NOT NULL,
    WEIGHT          DECIMAL(18,4)   NULL,
    SORT_ORDER      INT             NULL,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPM_EVAL_PARAM PRIMARY KEY (PARAM_ID),
    CONSTRAINT FK_QMS_SPM_PARAM_DEF FOREIGN KEY (DEF_ID) REFERENCES QMS_SPM_EVAL_DEF (DEF_ID),
    CONSTRAINT FK_QMS_SPM_PARAM_ITEM FOREIGN KEY (ITEM_ID) REFERENCES QMS_SPM_EVAL_ITEM (ITEM_ID)
);
CREATE INDEX IX_QMS_SPM_EVAL_PARAM_DEF ON QMS_SPM_EVAL_PARAM (DEF_ID, SORT_ORDER);

-- 협력사 평가 실적.
CREATE TABLE QMS_SPM_EVAL_RESULT (
    RESULT_ID       NVARCHAR(50)    NOT NULL,
    SUPPLIER_ID     NVARCHAR(50)    NOT NULL,
    SUPPLIER_NAME   NVARCHAR(200)   NULL,
    DEF_ID          NVARCHAR(50)    NULL,
    EVAL_PERIOD     NVARCHAR(50)    NULL,
    TOTAL_SCORE     DECIMAL(18,4)   NULL,
    GRADE           NVARCHAR(20)    NULL,
    EVALUATED_AT    DATETIME2       NOT NULL,
    EVALUATOR_ID    NVARCHAR(50)    NULL,
    REMARK          NVARCHAR(500)   NULL,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPM_EVAL_RESULT PRIMARY KEY (RESULT_ID)
);
CREATE INDEX IX_QMS_SPM_EVAL_RESULT_SUPPLIER ON QMS_SPM_EVAL_RESULT (SUPPLIER_ID, EVALUATED_AT DESC);

-- 시정 조치 결과.
CREATE TABLE QMS_SPM_ACTION_RESULT (
    ACTION_ID       NVARCHAR(50)    NOT NULL,
    RESULT_ID       NVARCHAR(50)    NULL,
    SUPPLIER_ID     NVARCHAR(50)    NOT NULL,
    ACTION_DESC     NVARCHAR(500)   NULL,
    ACTION_DATE     DATETIME2       NOT NULL,
    STATUS          NVARCHAR(20)    NOT NULL DEFAULT 'Open',
    COMPLETED_AT    DATETIME2       NULL,
    REMARK          NVARCHAR(500)   NULL,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_SPM_ACTION_RESULT PRIMARY KEY (ACTION_ID)
);
CREATE INDEX IX_QMS_SPM_ACTION_RESULT_SUPPLIER ON QMS_SPM_ACTION_RESULT (SUPPLIER_ID, ACTION_DATE DESC);
