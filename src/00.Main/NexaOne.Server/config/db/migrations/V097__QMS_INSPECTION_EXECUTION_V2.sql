-- QMS inspection execution v2: immutable multi-item result, idempotency, sampling snapshot,
-- and append-only cancellation/correction/reinspection history.
ALTER TABLE QMS_INSPECTION ADD
    LOT_QTY INT NULL,
    IDEMPOTENCY_KEY NVARCHAR(150) NULL,
    REQUEST_HASH CHAR(64) NULL,
    SAMPLING_PLAN_REVISION_ID NVARCHAR(50) NULL,
    SAMPLING_SNAPSHOT_JSON NVARCHAR(MAX) NULL,
    RELATION_TYPE NVARCHAR(20) NULL,
    PARENT_INSPECTION_ID NVARCHAR(50) NULL,
    ROOT_INSPECTION_ID NVARCHAR(50) NULL;

ALTER TABLE QMS_INSPECTION_RESULT ADD
    ITEM_SEQUENCE INT NULL,
    SAMPLE_QTY INT NULL,
    DEFECT_QTY INT NULL;

-- V093 enforced a legacy one-header/one-result relation. v2 uses one header with many items.
ALTER TABLE QMS_INSPECTION_RESULT DROP CONSTRAINT UQ_QMS_RESULT_INSPECTION;

CREATE UNIQUE INDEX UX_QMS_INSPECTION_IDEMPOTENCY
    ON QMS_INSPECTION (IDEMPOTENCY_KEY)
    WHERE IDEMPOTENCY_KEY IS NOT NULL;
CREATE UNIQUE INDEX UX_QMS_INSPECTION_RESULT_SEQUENCE
    ON QMS_INSPECTION_RESULT (INSPECTION_ID, ITEM_SEQUENCE)
    WHERE ITEM_SEQUENCE IS NOT NULL;
CREATE UNIQUE INDEX UX_QMS_INSPECTION_RESULT_SPEC
    ON QMS_INSPECTION_RESULT (INSPECTION_ID, SPEC_ID)
    WHERE ITEM_SEQUENCE IS NOT NULL;

ALTER TABLE QMS_INSPECTION ADD CONSTRAINT FK_QMS_INSPECTION_SAMPLING_REV
    FOREIGN KEY (SAMPLING_PLAN_REVISION_ID)
    REFERENCES QMS_SAMPLING_PLAN_REVISION (PLAN_REVISION_ID);
ALTER TABLE QMS_INSPECTION ADD CONSTRAINT FK_QMS_INSPECTION_PARENT
    FOREIGN KEY (PARENT_INSPECTION_ID) REFERENCES QMS_INSPECTION (INSPECTION_ID);
ALTER TABLE QMS_INSPECTION ADD CONSTRAINT FK_QMS_INSPECTION_ROOT
    FOREIGN KEY (ROOT_INSPECTION_ID) REFERENCES QMS_INSPECTION (INSPECTION_ID);
ALTER TABLE QMS_INSPECTION ADD CONSTRAINT CK_QMS_INSPECTION_V2
    CHECK (IDEMPOTENCY_KEY IS NULL OR
        (LEN(IDEMPOTENCY_KEY) > 0 AND REQUEST_HASH IS NOT NULL AND
         LEN(REQUEST_HASH) = 64 AND
         REQUEST_HASH COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^0-9A-Fa-f]%' AND
         LOT_ID IS NOT NULL AND EQUIPMENT_ID IS NOT NULL AND INSPECTOR_ID IS NOT NULL AND
         INSPECTION_TYPE IN ('Incoming', 'Process', 'Shipping') AND
         LOT_QTY IS NOT NULL AND LOT_QTY > 0 AND
         SAMPLE_QTY IS NOT NULL AND SAMPLE_QTY > 0 AND SAMPLE_QTY <= LOT_QTY AND
         DEFECT_QTY IS NOT NULL AND DEFECT_QTY >= 0 AND DEFECT_QTY <= SAMPLE_QTY AND
         RELATION_TYPE IN ('Original', 'Correction', 'Reinspection') AND
         ROOT_INSPECTION_ID IS NOT NULL AND
         ((RELATION_TYPE = 'Original' AND PARENT_INSPECTION_ID IS NULL) OR
          (RELATION_TYPE IN ('Correction', 'Reinspection') AND PARENT_INSPECTION_ID IS NOT NULL))));
ALTER TABLE QMS_INSPECTION_RESULT ADD CONSTRAINT CK_QMS_INSPECTION_RESULT_V2_QTY
    CHECK (ITEM_SEQUENCE IS NULL OR
        (ITEM_SEQUENCE > 0 AND SAMPLE_QTY IS NOT NULL AND SAMPLE_QTY > 0 AND
         DEFECT_QTY IS NOT NULL AND DEFECT_QTY >= 0 AND DEFECT_QTY <= SAMPLE_QTY));

CREATE TABLE QMS_INSPECTION_EVENT (
    EVENT_ID NVARCHAR(50) NOT NULL,
    INSPECTION_ID NVARCHAR(50) NOT NULL,
    EVENT_TYPE NVARCHAR(20) NOT NULL,
    RELATED_INSPECTION_ID NVARCHAR(50) NULL,
    PARENT_INSPECTION_ID NVARCHAR(50) NULL,
    ROOT_INSPECTION_ID NVARCHAR(50) NOT NULL,
    IDEMPOTENCY_KEY NVARCHAR(150) NOT NULL,
    REQUEST_HASH CHAR(64) NOT NULL,
    ACTOR_ID NVARCHAR(50) NOT NULL,
    REASON NVARCHAR(1000) NULL,
    OCCURRED_AT DATETIME2 NOT NULL,
    CREATED_BY NVARCHAR(50) NOT NULL,
    CREATED_AT DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_QMS_INSPECTION_EVENT PRIMARY KEY (EVENT_ID),
    CONSTRAINT UQ_QMS_INSPECTION_EVENT_KEY UNIQUE (INSPECTION_ID, IDEMPOTENCY_KEY),
    CONSTRAINT FK_QMS_INSPECTION_EVENT_EXEC FOREIGN KEY (INSPECTION_ID)
        REFERENCES QMS_INSPECTION (INSPECTION_ID),
    CONSTRAINT FK_QMS_INSPECTION_EVENT_RELATED FOREIGN KEY (RELATED_INSPECTION_ID)
        REFERENCES QMS_INSPECTION (INSPECTION_ID),
    CONSTRAINT FK_QMS_INSPECTION_EVENT_PARENT FOREIGN KEY (PARENT_INSPECTION_ID)
        REFERENCES QMS_INSPECTION (INSPECTION_ID),
    CONSTRAINT FK_QMS_INSPECTION_EVENT_ROOT FOREIGN KEY (ROOT_INSPECTION_ID)
        REFERENCES QMS_INSPECTION (INSPECTION_ID),
    CONSTRAINT FK_QMS_INSPECTION_EVENT_ACTOR FOREIGN KEY (ACTOR_ID)
        REFERENCES SYS_USER (USER_ID),
    CONSTRAINT CK_QMS_INSPECTION_EVENT_TYPE
        CHECK (EVENT_TYPE IN ('Confirmed', 'Cancelled', 'Corrected', 'Reinspected')),
    CONSTRAINT CK_QMS_INSPECTION_EVENT_HASH CHECK (LEN(REQUEST_HASH) = 64)
);
CREATE INDEX IX_QMS_INSPECTION_EVENT_TIME
    ON QMS_INSPECTION_EVENT (INSPECTION_ID, OCCURRED_AT, EVENT_ID);
CREATE UNIQUE INDEX UX_QMS_INSPECTION_EVENT_CANCELLED
    ON QMS_INSPECTION_EVENT (INSPECTION_ID)
    WHERE EVENT_TYPE = 'Cancelled';
CREATE INDEX IX_QMS_INSPECTION_ROOT
    ON QMS_INSPECTION (ROOT_INSPECTION_ID, INSPECTED_AT)
    WHERE ROOT_INSPECTION_ID IS NOT NULL;

