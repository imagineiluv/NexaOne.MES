-- BOM(제품 부품 구성) — 제품/부품 모두 MDM_PRODUCT 참조.
CREATE TABLE MDM_BOM (
    BOM_ID                  NVARCHAR(50)    NOT NULL,
    PRODUCT_ID              NVARCHAR(50)    NOT NULL,
    COMPONENT_ID            NVARCHAR(50)    NOT NULL,
    QUANTITY                DECIMAL(18,4)   NOT NULL DEFAULT 0,
    DESCRIPTION             NVARCHAR(500)   NULL,
    CREATED_BY              NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT              DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY              NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT              DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_MDM_BOM PRIMARY KEY (BOM_ID),
    CONSTRAINT FK_MDM_BOM_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES MDM_PRODUCT (PRODUCT_ID),
    CONSTRAINT FK_MDM_BOM_COMPONENT FOREIGN KEY (COMPONENT_ID)
        REFERENCES MDM_PRODUCT (PRODUCT_ID)
);
CREATE INDEX IX_MDM_BOM_PRODUCT ON MDM_BOM (PRODUCT_ID);

-- Qtime(공정별 표준작업시간) — 공정(MDM_SEGMENT) 참조(nullable).
CREATE TABLE MDM_QTIME (
    QTIME_ID                NVARCHAR(50)    NOT NULL,
    SEGMENT_ID              NVARCHAR(50)    NULL,
    STANDARD_TIME           DECIMAL(18,4)   NOT NULL DEFAULT 0,
    UNIT                    NVARCHAR(50)    NULL,
    DESCRIPTION             NVARCHAR(500)   NULL,
    CREATED_BY              NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT              DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY              NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT              DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_MDM_QTIME PRIMARY KEY (QTIME_ID),
    CONSTRAINT FK_MDM_QTIME_SEGMENT FOREIGN KEY (SEGMENT_ID)
        REFERENCES MDM_SEGMENT (SEGMENT_ID)
);
CREATE INDEX IX_MDM_QTIME_SEGMENT ON MDM_QTIME (SEGMENT_ID);

