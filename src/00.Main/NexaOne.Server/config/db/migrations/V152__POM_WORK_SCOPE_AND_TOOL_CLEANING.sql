EXEC(N'CREATE TRIGGER TR_POM_WORK_SCOPE_EXECUTION_APPEND_ONLY
ON POM_WORK_SCOPE_EXECUTION
AFTER UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    THROW 51520, ''POM_WORK_SCOPE_EXECUTION is append-only'', 1;
END');

EXEC(N'CREATE TRIGGER TR_POM_WORK_SCOPE_MEMBER_GUARD
ON POM_WORK_SCOPE_MEMBER
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS (
        SELECT 1
          FROM inserted I
          LEFT JOIN POM_WORK_SCOPE P ON P.WORK_SCOPE_ID = I.WORK_SCOPE_ID
          LEFT JOIN POM_WORK_SCOPE C ON C.WORK_SCOPE_ID = I.MEMBER_SCOPE_ID
         WHERE I.WORK_SCOPE_ID = I.MEMBER_SCOPE_ID
            OR I.SEQUENCE_NO <= 0
            OR P.WORK_SCOPE_ID IS NULL
            OR C.WORK_SCOPE_ID IS NULL
            OR P.PLANT_ID <> C.PLANT_ID
            OR I.MEMBER_TYPE <> C.SCOPE_TYPE
            OR I.MEMBER_TARGET_ID <> C.TARGET_ID
            OR ISNULL(C.PARENT_SCOPE_ID, '''') <> P.WORK_SCOPE_ID
            OR NOT (
                (P.SCOPE_TYPE = ''Campaign''
                    AND C.SCOPE_TYPE IN (''Batch'', ''Carrier'', ''Lot'', ''Other''))
                OR (P.SCOPE_TYPE = ''Batch''
                    AND C.SCOPE_TYPE IN (''Carrier'', ''Lot'', ''Other''))))
        THROW 51521, ''POM_WORK_SCOPE_MEMBER parent/child relationship is invalid'', 1;
END');

EXEC(N'CREATE TRIGGER TR_POM_WORK_SCOPE_MEMBER_APPEND_ONLY
ON POM_WORK_SCOPE_MEMBER
AFTER UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    THROW 51522, ''POM_WORK_SCOPE_MEMBER is append-only'', 1;
END');
