EXEC(N'CREATE TRIGGER TR_IVT_FEED_SESSION_RESERVE_LOT
ON IVT_MATERIAL_FEED_SESSION
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1 FROM inserted
         WHERE STATUS <> ''Mounted'' OR UNMOUNTED_AT IS NOT NULL OR UNMOUNTED_BY IS NOT NULL)
        THROW 51515, ''A feed session must begin Mounted and reserve its material LOT'', 1;

    UPDATE L
       SET ACTIVE_FEED_SESSION_ID = I.FEED_SESSION_ID,
           UPDATED_BY = I.MOUNTED_BY,
           UPDATED_AT = I.CREATED_AT
      FROM IVT_MATERIAL_LOT L
      JOIN inserted I
        ON I.MATERIAL_LOT_ID = L.LOT_ID
       AND I.MATERIAL_ID = L.MATERIAL_ID
     WHERE L.STATUS = ''InStock''
       AND L.CURRENT_QTY > 0
       AND L.ACTIVE_FEED_SESSION_ID IS NULL;

    DECLARE @ReservedRows INT = @@ROWCOUNT;
    IF @ReservedRows <> (SELECT COUNT(*) FROM inserted)
        THROW 51516, ''Feed-session material LOT reservation failed'', 1;
END');

EXEC(N'CREATE TRIGGER TR_IVT_MATERIAL_LOT_FEED_RESERVATION_GUARD
ON IVT_MATERIAL_LOT
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1
          FROM inserted I
          JOIN deleted D ON D.LOT_ID = I.LOT_ID
         WHERE D.ACTIVE_FEED_SESSION_ID IS NOT NULL
           AND (I.ACTIVE_FEED_SESSION_ID IS NULL
                OR I.ACTIVE_FEED_SESSION_ID COLLATE Latin1_General_100_BIN2
                   <> D.ACTIVE_FEED_SESSION_ID COLLATE Latin1_General_100_BIN2))
        THROW 51517, ''PendingDrain feed-session reservation cannot be cleared or replaced before durable finalization'', 1;

    IF EXISTS (
        SELECT 1
          FROM inserted I
          LEFT JOIN IVT_MATERIAL_FEED_SESSION S
            ON S.FEED_SESSION_ID = I.ACTIVE_FEED_SESSION_ID
           AND S.MATERIAL_LOT_ID = I.LOT_ID
         WHERE I.ACTIVE_FEED_SESSION_ID IS NOT NULL
           AND S.FEED_SESSION_ID IS NULL)
        THROW 51518, ''Material LOT reservation must reference a feed session for the same LOT'', 1;
END');
