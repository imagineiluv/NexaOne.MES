-- Owner: IVT. Versioned, replayable management commands for TRACE material bindings and feed sessions.
-- Binding mutation is additionally gated by the IVT application and is not an online-operation path.

ALTER TABLE IVT_TRACE_CONSUMPTION_BINDING ADD VERSION_NO INT NOT NULL DEFAULT 1;
ALTER TABLE IVT_MATERIAL_FEED_SESSION ADD VERSION_NO INT NOT NULL DEFAULT 1;
ALTER TABLE IVT_MATERIAL_LOT ADD ACTIVE_FEED_SESSION_ID NVARCHAR(50) NULL;
ALTER TABLE IVT_MATERIAL_CONSUMPTION_HISTORY ADD FEED_SESSION_ID NVARCHAR(50) NULL;

-- Do not guess physical attribution while collapsing the wider V114 source key or reserving a LOT.
-- The migration runner wraps this file in one transaction, so either preflight failure preserves
-- the original columns and V114 indexes.
-- SQLITE-OMIT-BEGIN
IF EXISTS (
    SELECT EQUIPMENT_ID, PARAMETER_ID
      FROM IVT_TRACE_CONSUMPTION_BINDING
     WHERE IS_ACTIVE = 1
     GROUP BY EQUIPMENT_ID, PARAMETER_ID
    HAVING COUNT_BIG(*) > 1)
    THROW 51513, 'V151 duplicate active TRACE source; resolve physical attribution before migration', 1;

IF EXISTS (
    SELECT MATERIAL_LOT_ID
      FROM IVT_MATERIAL_FEED_SESSION
     WHERE STATUS = 'Mounted' AND UNMOUNTED_AT IS NULL
     GROUP BY MATERIAL_LOT_ID
    HAVING COUNT_BIG(*) > 1)
    THROW 51514, 'V151 material LOT has multiple active feed sessions; resolve the physical mount before migration', 1;

-- V151 treats Unmounted as PendingDrain until a durable FDC upper-watermark finalizer exists.
-- A legacy closed interval has no trustworthy winner when several historical sessions share a LOT,
-- so migration must not guess or silently leave the material lifecycle unfenced.
IF EXISTS (
    SELECT 1
      FROM IVT_MATERIAL_FEED_SESSION
     WHERE STATUS = 'Unmounted' OR UNMOUNTED_AT IS NOT NULL)
    THROW 51519, 'V151 legacy Unmounted feed sessions require audited PendingDrain reconciliation before migration', 1;
-- SQLITE-OMIT-END

-- FDC source identity is Equipment+Parameter. Plant/feed point describe the downstream
-- attribution and must not permit the same physical sample to enter two bindings.
-- SQLITE-OMIT-BEGIN
DROP INDEX UX_IVT_TRACE_BINDING_ACTIVE_SOURCE ON IVT_TRACE_CONSUMPTION_BINDING;
DROP INDEX IX_IVT_TRACE_BINDING_SOURCE ON IVT_TRACE_CONSUMPTION_BINDING;
-- SQLITE-OMIT-END
CREATE UNIQUE INDEX UX_IVT_TRACE_BINDING_ACTIVE_SOURCE
    ON IVT_TRACE_CONSUMPTION_BINDING (EQUIPMENT_ID, PARAMETER_ID)
    WHERE IS_ACTIVE = 1;
CREATE INDEX IX_IVT_TRACE_BINDING_INTERVAL
    ON IVT_TRACE_CONSUMPTION_BINDING
       (EQUIPMENT_ID, PARAMETER_ID, EFFECTIVE_TO);

-- A physical material LOT can be mounted in one feed session at a time. The LOT-side
-- reservation gives Mount and inventory lifecycle commands one atomic CAS row.
CREATE UNIQUE INDEX UX_IVT_FEED_SESSION_ACTIVE_LOT
    ON IVT_MATERIAL_FEED_SESSION (MATERIAL_LOT_ID)
    WHERE STATUS = 'Mounted' AND UNMOUNTED_AT IS NULL;

-- ACTIVE_FEED_SESSION_ID is also retained after Unmount while late pre-cutoff TRACE drains.
-- A composite candidate key lets the LOT-side reservation prove that the referenced session
-- belongs to that same material LOT instead of merely pointing at any existing session.
CREATE UNIQUE INDEX UX_IVT_FEED_SESSION_ID_MATERIAL_LOT
    ON IVT_MATERIAL_FEED_SESSION (FEED_SESSION_ID, MATERIAL_LOT_ID);

UPDATE IVT_MATERIAL_LOT
   SET ACTIVE_FEED_SESSION_ID = (
       SELECT S.FEED_SESSION_ID
         FROM IVT_MATERIAL_FEED_SESSION S
        WHERE S.MATERIAL_LOT_ID = IVT_MATERIAL_LOT.LOT_ID
          AND S.STATUS = 'Mounted' AND S.UNMOUNTED_AT IS NULL)
 WHERE EXISTS (
       SELECT 1 FROM IVT_MATERIAL_FEED_SESSION S
        WHERE S.MATERIAL_LOT_ID = IVT_MATERIAL_LOT.LOT_ID
          AND S.STATUS = 'Mounted' AND S.UNMOUNTED_AT IS NULL);

CREATE UNIQUE INDEX UX_IVT_MATERIAL_LOT_ACTIVE_FEED_SESSION
    ON IVT_MATERIAL_LOT (ACTIVE_FEED_SESSION_ID)
    WHERE ACTIVE_FEED_SESSION_ID IS NOT NULL;

-- Preserve V137 append-only evidence: legacy TRACE rows keep their historical feed-session
-- identity in CORRELATION_ID. Only new consumption writes populate the typed FEED_SESSION_ID.
-- SQLITE-OMIT-BEGIN
ALTER TABLE IVT_MATERIAL_LOT ADD CONSTRAINT
    FK_IVT_MATERIAL_LOT_ACTIVE_FEED_SESSION FOREIGN KEY (ACTIVE_FEED_SESSION_ID, LOT_ID)
    REFERENCES IVT_MATERIAL_FEED_SESSION (FEED_SESSION_ID, MATERIAL_LOT_ID);
-- SQLITE-OMIT-END

ALTER TABLE IVT_MATERIAL_CONSUMPTION_HISTORY ADD CONSTRAINT
    FK_IVT_MATERIAL_CONSUMPTION_FEED_SESSION FOREIGN KEY (FEED_SESSION_ID, MATERIAL_LOT_ID)
    REFERENCES IVT_MATERIAL_FEED_SESSION (FEED_SESSION_ID, MATERIAL_LOT_ID);

CREATE INDEX IX_IVT_MATERIAL_CONSUMPTION_FEED_SESSION
    ON IVT_MATERIAL_CONSUMPTION_HISTORY (FEED_SESSION_ID)
    WHERE FEED_SESSION_ID IS NOT NULL;

