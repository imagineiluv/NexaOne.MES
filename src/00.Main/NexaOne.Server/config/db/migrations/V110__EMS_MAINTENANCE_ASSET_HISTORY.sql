    EQUIPMENT_ID   NVARCHAR(50)    NOT NULL,
    WO_ID          NVARCHAR(50)    NULL,
    QUANTITY       DECIMAL(18,4)   NOT NULL,
    USED_BY        NVARCHAR(50)    NOT NULL,
    USED_AT        DATETIME2       NOT NULL,
    REMOVAL_REASON NVARCHAR(500)   NULL,
    SERIAL_NO      NVARCHAR(100)   NULL,
    LOT_NO         NVARCHAR(100)   NULL,
    CREATED_BY     NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT     DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_EMS_SPARE_PART_USAGE PRIMARY KEY (USAGE_ID),
    CONSTRAINT FK_EMS_SPARE_USAGE_INOUT FOREIGN KEY (INOUT_ID) REFERENCES EMS_SPARE_PART_INOUT (INOUT_ID),
    CONSTRAINT FK_EMS_SPARE_USAGE_PART FOREIGN KEY (PART_ID) REFERENCES EMS_SPARE_PART (PART_ID),
    CONSTRAINT FK_EMS_SPARE_USAGE_BOM FOREIGN KEY (BOM_ITEM_ID) REFERENCES EMS_EQUIPMENT_PART_BOM (BOM_ITEM_ID),
    CONSTRAINT FK_EMS_SPARE_USAGE_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID) REFERENCES MDM_EQUIPMENT (EQUIPMENT_ID),
    CONSTRAINT FK_EMS_SPARE_USAGE_WO FOREIGN KEY (WO_ID) REFERENCES EMS_WORK_ORDER (WO_ID),
    CONSTRAINT CK_EMS_SPARE_USAGE_QUANTITY CHECK (QUANTITY > 0)
);
CREATE UNIQUE INDEX UX_EMS_SPARE_USAGE_INOUT ON EMS_SPARE_PART_USAGE (INOUT_ID);
CREATE INDEX IX_EMS_SPARE_USAGE_PART ON EMS_SPARE_PART_USAGE (PART_ID, USED_AT DESC);
CREATE INDEX IX_EMS_SPARE_USAGE_EQUIPMENT ON EMS_SPARE_PART_USAGE (EQUIPMENT_ID, USED_AT DESC);

