    ON EMS_EQUIPMENT_PART_BOM (EQUIPMENT_CLASS_ID, PART_ID);
CREATE UNIQUE INDEX UX_EMS_EQUIPMENT_PART_BOM_IDEMPOTENCY
    ON EMS_EQUIPMENT_PART_BOM (LAST_IDEMPOTENCY_KEY)
    WHERE LAST_IDEMPOTENCY_KEY <> '';

-- 실제 부품 사용 원장. V110에서 처음 생성되는 신규 테이블이므로 INOUT_ID를 nullable legacy
