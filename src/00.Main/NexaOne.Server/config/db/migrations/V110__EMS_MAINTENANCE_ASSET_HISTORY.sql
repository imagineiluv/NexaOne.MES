    CONSTRAINT FK_EMS_TOOL_EQUIPMENT_CLASS FOREIGN KEY (EQUIPMENT_CLASS_ID)
        REFERENCES MDM_EQUIPMENT_CLASS (EQUIPMENT_CLASS_ID),
    CONSTRAINT CK_EMS_TOOL_STATUS CHECK (
        STATUS IN ('Available', 'Mounted', 'Due', 'Blocked', 'Retired')),
