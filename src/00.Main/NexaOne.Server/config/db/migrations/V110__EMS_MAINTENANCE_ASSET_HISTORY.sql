-- EMS 보전/예비부품/생산툴 공통 원장. 기존 EMS_WORK_ORDER, EMS_MAINTENANCE_PLAN,
-- EMS_SPARE_PART, EMS_SPARE_PART_INOUT을 대체하지 않고 누락된 작업자 행동 증거와 계획 데이터를 보강한다.

-- 로그인 작업자가 수행한 보전 W/O 행동의 append-only 증거. ASSIGNEE_ID(담당 예정자)와
-- ACTOR_ID(실제 실행자)를 분리해 수동 운전 감사가 mutable UPDATED_BY 한 칸에 덮어써지지 않게 한다.
CREATE TABLE EMS_MAINTENANCE_ACTION_HISTORY (
    ACTION_ID       NVARCHAR(50)    NOT NULL,
    WO_ID           NVARCHAR(50)    NULL,
    MAINTENANCE_PLAN_ID NVARCHAR(50) NULL,
    EQUIPMENT_ID    NVARCHAR(50)    NOT NULL,
    MAINTENANCE_TYPE NVARCHAR(20)   NOT NULL,
    ACTION_TYPE     NVARCHAR(30)    NOT NULL,
    RESULT_STATUS   NVARCHAR(20)    NOT NULL,
    ACTOR_ID        NVARCHAR(50)    NOT NULL,
    ASSIGNEE_ID     NVARCHAR(50)    NULL,
    SOURCE          NVARCHAR(20)    NOT NULL DEFAULT 'Manual',
    CLIENT_CHANNEL  NVARCHAR(20)    NOT NULL DEFAULT 'MES',
    DEVICE_ID       NVARCHAR(100)   NULL,
    FAILURE_CODE_ID NVARCHAR(50)    NULL,
    REMARK          NVARCHAR(500)   NULL,
    ACTION_AT       DATETIME2       NOT NULL,
    CREATED_BY      NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT      DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_EMS_MAINTENANCE_ACTION PRIMARY KEY (ACTION_ID),
    CONSTRAINT FK_EMS_MAINT_ACTION_WO FOREIGN KEY (WO_ID) REFERENCES EMS_WORK_ORDER (WO_ID),
    CONSTRAINT FK_EMS_MAINT_ACTION_PLAN FOREIGN KEY (MAINTENANCE_PLAN_ID)
        REFERENCES EMS_MAINTENANCE_PLAN (PLAN_ID)
);
CREATE INDEX IX_EMS_MAINT_ACTION_WO
    ON EMS_MAINTENANCE_ACTION_HISTORY (WO_ID, ACTION_AT DESC);
CREATE INDEX IX_EMS_MAINT_ACTION_EQUIPMENT
    ON EMS_MAINTENANCE_ACTION_HISTORY (EQUIPMENT_ID, ACTION_AT DESC);
CREATE INDEX IX_EMS_MAINT_ACTION_ACTOR
    ON EMS_MAINTENANCE_ACTION_HISTORY (ACTOR_ID, ACTION_AT DESC);

-- 적정재고/최적화 입력값. EMS_SPARE_PART의 MIN/MAX는 현재 운영 한계값으로 유지하고,
-- 수요·서비스수준·재주문 계산 파라미터는 별도 정책 행으로 버전 독립 관리한다.
CREATE TABLE EMS_SPARE_PART_STOCK_POLICY (
    PART_ID              NVARCHAR(50)    NOT NULL,
    SAFETY_STOCK         DECIMAL(18,4)   NOT NULL DEFAULT 0,
    REORDER_POINT        DECIMAL(18,4)   NOT NULL DEFAULT 0,
    TARGET_STOCK         DECIMAL(18,4)   NOT NULL DEFAULT 0,
    RESERVED_QTY         DECIMAL(18,4)   NOT NULL DEFAULT 0,
    AVG_DAILY_USAGE      DECIMAL(18,6)   NOT NULL DEFAULT 0,
    SERVICE_LEVEL        DECIMAL(8,4)    NULL,
    REVIEW_CYCLE_DAYS    INT             NULL,
    IS_ACTIVE            BIT             NOT NULL DEFAULT 1,
    VERSION_NO           INT             NOT NULL DEFAULT 1,
    LAST_IDEMPOTENCY_KEY NVARCHAR(100)   NOT NULL DEFAULT '',
    LAST_REQUEST_HASH    NVARCHAR(128)   NOT NULL DEFAULT '',
    CREATED_BY           NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT           DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY           NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT           DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_EMS_SPARE_STOCK_POLICY PRIMARY KEY (PART_ID),
    CONSTRAINT FK_EMS_SPARE_STOCK_POLICY_PART FOREIGN KEY (PART_ID) REFERENCES EMS_SPARE_PART (PART_ID),
    CONSTRAINT CK_EMS_SPARE_STOCK_POLICY_VALUES CHECK (
        SAFETY_STOCK >= 0 AND REORDER_POINT >= 0 AND TARGET_STOCK >= SAFETY_STOCK
        AND TARGET_STOCK >= REORDER_POINT AND RESERVED_QTY >= 0 AND AVG_DAILY_USAGE >= 0
        AND (SERVICE_LEVEL IS NULL OR (SERVICE_LEVEL >= 0 AND SERVICE_LEVEL <= 1))
        AND (REVIEW_CYCLE_DAYS IS NULL OR REVIEW_CYCLE_DAYS > 0)
        AND VERSION_NO > 0)
);
CREATE UNIQUE INDEX UX_EMS_SPARE_STOCK_POLICY_IDEMPOTENCY
    ON EMS_SPARE_PART_STOCK_POLICY (LAST_IDEMPOTENCY_KEY)
    WHERE LAST_IDEMPOTENCY_KEY <> '';

-- 부품별 복수 공급처와 조달 조건. 공급처 마스터는 MDM_VENDOR를 문자열로 느슨 참조해 모듈 배포 독립성을 유지한다.
CREATE TABLE EMS_SPARE_PART_SUPPLIER (
    PART_SUPPLIER_ID NVARCHAR(50)    NOT NULL,
    PART_ID          NVARCHAR(50)    NOT NULL,
    VENDOR_ID        NVARCHAR(50)    NOT NULL,
    VENDOR_PART_NO   NVARCHAR(100)   NULL,
    LEAD_TIME_DAYS   INT             NOT NULL DEFAULT 0,
    MOQ              DECIMAL(18,4)   NULL,
    UNIT_PRICE       DECIMAL(18,4)   NULL,
    CURRENCY         NVARCHAR(10)    NULL,
    IS_PRIMARY       BIT             NOT NULL DEFAULT 0,
    IS_ACTIVE        BIT             NOT NULL DEFAULT 1,
    VERSION_NO       INT             NOT NULL DEFAULT 1,
    LAST_IDEMPOTENCY_KEY NVARCHAR(100) NOT NULL DEFAULT '',
    LAST_REQUEST_HASH NVARCHAR(128)  NOT NULL DEFAULT '',
    CREATED_BY       NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT       DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY       NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT       DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_EMS_SPARE_PART_SUPPLIER PRIMARY KEY (PART_SUPPLIER_ID),
    CONSTRAINT FK_EMS_SPARE_PART_SUPPLIER_PART FOREIGN KEY (PART_ID) REFERENCES EMS_SPARE_PART (PART_ID),
    CONSTRAINT FK_EMS_SPARE_PART_SUPPLIER_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES MDM_VENDOR (VENDOR_ID),
    CONSTRAINT CK_EMS_SPARE_PART_SUPPLIER_VALUES CHECK (
        LEAD_TIME_DAYS >= 0 AND (MOQ IS NULL OR MOQ > 0)
        AND (UNIT_PRICE IS NULL OR UNIT_PRICE >= 0)
        AND ((UNIT_PRICE IS NULL AND CURRENCY IS NULL) OR (UNIT_PRICE IS NOT NULL AND CURRENCY IS NOT NULL))
        AND (IS_PRIMARY = 0 OR IS_ACTIVE = 1) AND VERSION_NO > 0)
);
CREATE UNIQUE INDEX UX_EMS_SPARE_PART_VENDOR
    ON EMS_SPARE_PART_SUPPLIER (PART_ID, VENDOR_ID);
CREATE INDEX IX_EMS_SPARE_PART_LEAD_TIME
    ON EMS_SPARE_PART_SUPPLIER (PART_ID, IS_ACTIVE, LEAD_TIME_DAYS);
CREATE UNIQUE INDEX UX_EMS_SPARE_PART_PRIMARY_ACTIVE
    ON EMS_SPARE_PART_SUPPLIER (PART_ID)
    WHERE IS_PRIMARY = 1 AND IS_ACTIVE = 1;
CREATE UNIQUE INDEX UX_EMS_SPARE_PART_SUPPLIER_IDEMPOTENCY
    ON EMS_SPARE_PART_SUPPLIER (LAST_IDEMPOTENCY_KEY)
    WHERE LAST_IDEMPOTENCY_KEY <> '';

-- 설비/설비등급 BOM과 예비부품 연결. EQUIPMENT_ID와 EQUIPMENT_CLASS_ID 중 실제 적용 범위만 채운다.
