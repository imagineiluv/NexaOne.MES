    EQUIPMENT_CLASS_ID   NVARCHAR(50)    NULL,
    PART_ID              NVARCHAR(50)    NOT NULL,
    QUANTITY_PER         DECIMAL(18,4)   NOT NULL DEFAULT 1,
    CRITICALITY          NVARCHAR(20)    NULL,
    REPLACEMENT_CYCLE_DAYS INT           NULL,
    REPLACEMENT_CYCLE_COUNT DECIMAL(18,4) NULL,
    POSITION_CODE        NVARCHAR(100)   NULL,
    IS_ACTIVE            BIT             NOT NULL DEFAULT 1,
    VERSION_NO           INT             NOT NULL DEFAULT 1,
    LAST_IDEMPOTENCY_KEY NVARCHAR(100)   NOT NULL DEFAULT '',
    LAST_REQUEST_HASH    NVARCHAR(128)   NOT NULL DEFAULT '',
    CREATED_BY           NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    CREATED_AT           DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    UPDATED_BY           NVARCHAR(50)    NOT NULL DEFAULT 'SYSTEM',
    UPDATED_AT           DATETIME2       NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_EMS_EQUIPMENT_PART_BOM PRIMARY KEY (BOM_ITEM_ID),
    CONSTRAINT FK_EMS_EQUIPMENT_PART_BOM_PART FOREIGN KEY (PART_ID) REFERENCES EMS_SPARE_PART (PART_ID),
    CONSTRAINT FK_EMS_EQUIPMENT_PART_BOM_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID) REFERENCES MDM_EQUIPMENT (EQUIPMENT_ID),
    CONSTRAINT FK_EMS_EQUIPMENT_PART_BOM_CLASS FOREIGN KEY (EQUIPMENT_CLASS_ID) REFERENCES MDM_EQUIPMENT_CLASS (EQUIPMENT_CLASS_ID),
    CONSTRAINT CK_EMS_EQUIPMENT_PART_BOM_SCOPE CHECK (
        (EQUIPMENT_ID IS NOT NULL AND EQUIPMENT_CLASS_ID IS NULL)
        OR (EQUIPMENT_ID IS NULL AND EQUIPMENT_CLASS_ID IS NOT NULL)),
    CONSTRAINT CK_EMS_EQUIPMENT_PART_BOM_VALUES CHECK (
        QUANTITY_PER > 0
        AND (CRITICALITY IS NULL OR CRITICALITY IN ('Critical', 'High', 'Medium', 'Low'))
        AND (REPLACEMENT_CYCLE_DAYS IS NULL OR REPLACEMENT_CYCLE_DAYS > 0)
        AND (REPLACEMENT_CYCLE_COUNT IS NULL OR REPLACEMENT_CYCLE_COUNT > 0)
        AND VERSION_NO > 0)
