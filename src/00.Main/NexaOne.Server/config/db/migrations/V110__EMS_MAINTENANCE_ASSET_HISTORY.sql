    LAST_INSPECTED_AT  DATETIME2       NULL,
    LAST_CALIBRATED_AT DATETIME2       NULL,
    NEXT_INSPECTION_DUE_AT DATETIME2   NULL,
    NEXT_CALIBRATION_DUE_AT DATETIME2  NULL,
