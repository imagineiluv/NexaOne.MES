        (MAX_USE_COUNT IS NULL OR MAX_USE_COUNT >= 0)
        AND (MAX_USE_MINUTES IS NULL OR MAX_USE_MINUTES >= 0)
        AND CURRENT_USE_COUNT >= 0 AND CURRENT_USE_MINUTES >= 0),
    CONSTRAINT CK_EMS_TOOL_CYCLE CHECK (
        (INSPECTION_CYCLE_DAYS IS NULL OR INSPECTION_CYCLE_DAYS > 0)
        AND (CALIBRATION_CYCLE_DAYS IS NULL OR CALIBRATION_CYCLE_DAYS > 0))
