-- Owner: EMS. Maintenance-plan scope, spare opening balance, and tool chronology guards.

ALTER TABLE EMS_SPARE_PART_INOUT DROP CONSTRAINT CK_EMS_SPARE_PART_INOUT_EXECUTION;

ALTER TABLE EMS_SPARE_PART_INOUT ADD CONSTRAINT CK_EMS_SPARE_PART_INOUT_EXECUTION CHECK (
    IDEMPOTENCY_KEY IS NULL
    OR (QUANTITY IS NOT NULL
        AND ((TRANSACTION_TYPE = 'Opening' AND QUANTITY >= 0
              AND BALANCE_BEFORE = 0 AND BALANCE_AFTER = QUANTITY
              AND WO_ID IS NULL AND EQUIPMENT_ID IS NULL)
             OR (TRANSACTION_TYPE <> 'Opening' AND QUANTITY > 0))
        AND BALANCE_BEFORE IS NOT NULL AND BALANCE_BEFORE >= 0
        AND BALANCE_AFTER IS NOT NULL AND BALANCE_AFTER >= 0
        AND PROCESSED_BY IS NOT NULL
        AND CLIENT_CHANNEL IN ('MES', 'MOBILE', 'POP'))
);

